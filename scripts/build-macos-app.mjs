import { cpSync, chmodSync, mkdirSync, realpathSync, existsSync, writeFileSync, renameSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
if (process.platform !== 'darwin') throw new Error('Build the macOS app on macOS.');
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version=require('../package.json').version;
const output = resolve(process.argv[2] || join(root, '..', 'QH.app'));
if (!output.endsWith('.app') || existsSync(output)) throw new Error(`Choose a new .app output path: ${output}`);
execFileSync('bun', ['build', join(root, 'desktop/renderer.js'), '--target=browser', '--outfile', join(root, 'desktop/renderer.bundle.js')], { stdio: 'inherit' });
execFileSync('bun',['build',join(root,'desktop/settings-renderer.js'),'--target=browser','--outfile',join(root,'desktop/settings.bundle.js')],{stdio:'inherit'});
cpSync(join(root, 'node_modules/@xterm/xterm/css/xterm.css'), join(root, 'desktop/xterm.css'));
const electronApp = join(dirname(require.resolve('electron/package.json')), 'dist/Electron.app');
cpSync(electronApp, output, { recursive: true, verbatimSymlinks: true });
const resources = join(output, 'Contents/Resources');
const appSource = join(resources, 'app'); mkdirSync(appSource);
cpSync(join(root, 'desktop'), appSource, { recursive: true });
writeFileSync(join(appSource, 'package.json'), JSON.stringify({ name: 'qh', version, main: 'main.cjs' }));
const project = join(resources, 'terminal'); mkdirSync(project);
for (const item of ['src', 'desktop', 'lib', 'bin', 'scripts', 'package.json', 'bun.lock', 'README.md', 'docs', 'LICENSE', 'NOTICE.md']) cpSync(join(root, item), join(project, item), { recursive: true, dereference: true });
cpSync(join(root, 'node_modules'), join(project, 'node_modules'), { recursive: true, dereference: true, filter: path => !path.startsWith(join(root, 'node_modules/electron')) });
const runtime = join(resources, 'runtime'); mkdirSync(runtime);
const bun = realpathSync(execFileSync('/usr/bin/which', ['bun'], { encoding: 'utf8' }).trim());
cpSync(bun, join(runtime, 'bun')); cpSync(realpathSync(process.execPath), join(runtime, 'node'));
for (const name of ['bun','node']) chmodSync(join(runtime,name),0o755);
cpSync(join(root, 'src/assets/icons/QH.icns'), join(resources, 'QH.icns'));
renameSync(join(output, 'Contents/MacOS/Electron'), join(output, 'Contents/MacOS/QH'));
const plist = join(output, 'Contents/Info.plist');
for (const [key,value] of Object.entries({ CFBundleName:'QH', CFBundleDisplayName:'QH', CFBundleIdentifier:'com.qentrah.qh', CFBundleExecutable:'QH', CFBundleIconFile:'QH.icns', CFBundleShortVersionString:version, CFBundleVersion:version.replaceAll('.',''), NSHumanReadableCopyright:'QH. Third-party licenses are included in Resources.' })) execFileSync('/usr/bin/plutil',['-replace',key,'-string',value,plist]);
execFileSync('/usr/bin/codesign',['--force','--deep','--sign','-','--entitlements',join(root,'scripts/mac-entitlements.plist'),output],{stdio:'inherit'});
execFileSync('/usr/bin/codesign',['--verify','--deep','--strict',output],{stdio:'inherit'});
const configurationPath = join(dirname(output), 'qh.config.json');
if (!existsSync(configurationPath)) cpSync(join(root, 'qh.config.json'), configurationPath);
console.log(`Built standalone desktop app: ${output}`);
