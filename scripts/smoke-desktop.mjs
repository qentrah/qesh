import { spawn } from 'node:child_process';
import { createInterface } from 'node:readline';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import Xterm from '@xterm/headless';
const hostPath = process.env.QENTRAH_DESKTOP_HOST || fileURLToPath(new URL('../desktop/host.mjs', import.meta.url));
const terminal = new Xterm.Terminal({ cols: 110, rows: 30, allowProposedApi: true });
const host = spawn(process.env.QENTRAH_NODE || 'node', [hostPath], { env: { ...process.env, QH_PERSIST: '0', QENTRAH_START_DIR: process.cwd() }, stdio: 'pipe' });
let closed, failure, workspace;
const send = message => host.stdin.write(JSON.stringify(message) + '\n');
terminal.onData(data => send({ type: 'input', data }));
createInterface({ input: host.stdout }).on('line', line => {
 const message = JSON.parse(line);
 if (message.type === 'output') terminal.write(message.data, () => send({ type: 'ack', size: message.data.length }));
 if (message.type === 'state') workspace = message;
 if (message.type === 'error') failure = message.message;
});
host.stderr.on('data', data => { failure = String(data); });
host.on('exit', code => { closed = code; });
const frame = () => Array.from({ length: terminal.rows }, (_, y) => terminal.buffer.active.getLine(terminal.buffer.active.baseY + y)?.translateToString(true) || '').join('\n');
async function until(check) { const deadline = Date.now() + 12000; while (!check()) { if (failure) throw new Error(failure); if (Date.now() > deadline) throw new Error(`Desktop smoke timed out\n${frame()}`); await new Promise(resolve => setTimeout(resolve, 25)); } }
try {
 send({ type: 'start', cols: 110, rows: 30 });
 await until(() => frame().includes('Ctrl+B'));
 send({ type: 'input', data: 'echo typing' });
 await until(() => frame().includes('echo typing'));
 const row = terminal.buffer.active.getLine(terminal.buffer.active.baseY + terminal.buffer.active.cursorY).translateToString(true);
 assert.ok(row.includes('echo typing'), 'Host cursor must be on the row being typed');
 assert.equal(terminal.buffer.active.cursorX, row.lastIndexOf('echo typing') + 'echo typing'.length, 'Cursor must follow typed text');
 send({ type: 'input', data: '\x15printf "\\nDESKTOP-PID-%s\\n" $$\r' });
 await until(() => /DESKTOP-PID-\d+/.test(frame()));
 const pid = Number(frame().match(/DESKTOP-PID-(\d+)/)[1]);
 terminal.resize(70, 20); send({ type: 'resize', cols: 70, rows: 20 });
 await new Promise(resolve => setTimeout(resolve, 150));
 send({ type: 'input', data: 'printf "\\nRESIZED-%s-" $$; stty size\r' });
 await until(() => frame().includes(`RESIZED-${pid}-16 70`));
 assert.ok(frame().includes(`RESIZED-${pid}-16 70`));
 await until(() => workspace?.tabs.length === 1);
 const originalTab = workspace.active;
 send({type:'control',command:{action:'new-group',name:'Projects'}});
 send({type:'control',command:{action:'new-tab'}});
 await until(() => workspace.tabs.length===2 && workspace.tabs[1].sessions[0].status==='running');
 const movedTab=workspace.active, secondPid=workspace.tabs[1].sessions[0].pid;
 send({type:'control',command:{action:'group-tab',id:movedTab,group:'Projects'}});
 await until(() => workspace.tabs.find(tab=>tab.id===movedTab).group==='Projects');
 send({type:'control',command:{action:'switch-tab',id:originalTab}});
 send({type:'control',command:{action:'dock-tab',id:movedTab,edge:'right'}});
 await until(() => workspace.tabs.length===1 && workspace.tabs[0].sessions.length===2);
 assert.ok(workspace.tabs[0].sessions.some(session=>session.pid===pid));
 assert.ok(workspace.tabs[0].sessions.some(session=>session.pid===secondPid));
 const pane=workspace.tabs[0].sessions.find(session=>session.pid===secondPid).id;
 send({type:'control',command:{action:'detach-pane',id:pane}});
 await until(() => workspace.tabs.length===2);
 send({ type: 'input', data: '\x02q' }); await until(() => frame().includes('Quit QH?'));
 send({ type: 'input', data: '\t' }); await new Promise(resolve => setTimeout(resolve, 60));send({ type: 'input', data: '\r' });
 send({ type: 'shutdown' }); await until(() => closed !== undefined);
 assert.equal(closed, 0);
 assert.throws(() => process.kill(pid, 0), 'Desktop quit must clean up shell');
 assert.throws(() => process.kill(secondPid,0), 'Grouped and docked shell must also be cleaned up');
 console.log('Desktop smoke passed: typing, cursor, resize, groups, dock/detach with preserved PIDs, and cleanup.');
} finally { if (closed === undefined) { send({ type: 'shutdown' }); host.stdin.end(); } terminal.dispose(); }
